export function getTicketsCSV(): string {
  const headers = ['ID', 'Titulo', 'Categoria', 'Prioridade', 'Status', 'Tempo_Horas', 'SLA_Cumprido', 'Departamento', 'Tecnico', 'Data_Abertura', 'CSAT'];
  const rows = TICKETS_DATA.map(t => [
    t.id,
    `"${t.titulo.replace(/"/g, '""')}"`,
    t.categoria,
    t.prioridade,
    t.status,
    t.tempo_horas.toString(),
    t.sla_cumprido ? 'Sim' : 'Não',
    t.departamento,
    t.tecnico,
    t.data_abertura,
    t.csat.toString()
  ].join(','));
  return [headers.join(','), ...rows].join('\n');
}

